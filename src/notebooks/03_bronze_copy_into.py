# Databricks notebook source
# MAGIC %md
# MAGIC # 03 – Bronze: chunk 1 CSV via COPY INTO
# MAGIC
# MAGIC **Purpose:** load the chunk 1 CSV files (Apr 2019) from the Bronze `raw_files` volume into the Delta
# MAGIC table `rain_forecast_chunk1_csv`, as-is, with audit columns.
# MAGIC
# MAGIC **Steps**
# MAGIC 1. Create the table if needed (explicit schema, description on the table and every column,
# MAGIC    Liquid Clustering) and re-apply the descriptions.
# MAGIC 2. `COPY INTO` – every value is read as text and cast explicitly (no `inferSchema`). The CSV reader
# MAGIC    matches columns **by header name**, so the 4 files with 27 columns load with null satellite bands.
# MAGIC 3. `OPTIMIZE` to cluster the new data (optional).
# MAGIC 4. Sanity checks – the notebook **fails** if any check fails.
# MAGIC
# MAGIC **Rerunnable:** COPY INTO remembers which files it has already loaded into this table, so a second
# MAGIC run loads 0 rows. Bronze keeps values exactly as in the source (e.g. `CIN = 9999`, band = 0);
# MAGIC Silver cleans them.

# COMMAND ----------

# MAGIC %md
# MAGIC ## Parameters
# MAGIC
# MAGIC When run as a job, these come from bundle variables. `load_run_id` is the job run ID; when the
# MAGIC notebook is run by hand it is empty and becomes `manual`.

# COMMAND ----------

dbutils.widgets.text("catalog", "workspace", "Catalog")
dbutils.widgets.text("bronze_schema", "vstone_dev_bronze", "Bronze schema")
dbutils.widgets.text("raw_volume", "raw_files", "Raw (chunk) volume")
dbutils.widgets.text("chunk_name", "chunk1_csv", "Chunk folder")
dbutils.widgets.text("table_name", "rain_forecast_chunk1_csv", "Bronze table")
dbutils.widgets.text("cluster_by", "day,hour", "Liquid Clustering columns")
dbutils.widgets.text("load_run_id", "", "Load run ID (job run ID)")
dbutils.widgets.dropdown("run_optimize", "true", ["true", "false"], "Run OPTIMIZE")

params = {
    name: dbutils.widgets.get(name).strip()
    for name in ["catalog", "bronze_schema", "raw_volume", "chunk_name", "table_name", "cluster_by", "load_run_id", "run_optimize"]
}
empty = [n for n, v in params.items() if not v and n != "load_run_id"]
if empty:
    raise ValueError(f"These widgets must not be empty: {empty}")

# COMMAND ----------

import os
import sys

from pyspark.sql import functions as F

src_root = os.path.abspath(os.path.join(os.getcwd(), ".."))
if src_root not in sys.path:
    sys.path.insert(0, src_root)

from common.copy_into import INGESTION_METHOD, build_copy_into_sql, resolve_run_id
from common.rain_schema import (
    NATURAL_KEY,
    SATELLITE_BANDS,
    comment_sql,
    create_table_sql,
    full_table_name,
    quote_identifier,
)
from common.source_reader import FILE_NAME_COLUMN, parse_header, read_csv_by_name

table = full_table_name(params["catalog"], params["bronze_schema"], params["table_name"])
source_dir = f"/Volumes/{params['catalog']}/{params['bronze_schema']}/{params['raw_volume']}/chunks/{params['chunk_name']}"
cluster_by = [c.strip() for c in params["cluster_by"].split(",") if c.strip()]
run_id = resolve_run_id(params["load_run_id"])
table_comment = (
    f"Bronze: Rain Forecast {params['chunk_name']} loaded as-is with COPY INTO from {source_dir}. "
    "One row per grid cell per hour; natural key row, col, year, month, day, hour. "
    "Values kept exactly as in the source (CIN = 9999 and satellite band = 0 mean missing; "
    "satellite bands are null for source files without satellite columns)."
)

print(f"Table      : {table}")
print(f"Source     : {source_dir}")
print(f"Clustering : {cluster_by}")
print(f"Run ID     : {run_id}")

# COMMAND ----------

# MAGIC %md
# MAGIC ## Step 1 – Create the table and apply descriptions
# MAGIC
# MAGIC `CREATE TABLE IF NOT EXISTS` does nothing when the table already exists, so the descriptions and
# MAGIC clustering are re-applied every run. That keeps the table in sync with `src/common/rain_schema.py`.

# COMMAND ----------

spark.sql(create_table_sql(table, table_comment, cluster_by))
spark.sql(f"ALTER TABLE {table} CLUSTER BY ({', '.join(quote_identifier(c) for c in cluster_by)})")
for statement in comment_sql(table, table_comment):
    spark.sql(statement)

display(spark.sql(f"DESCRIBE TABLE {table}"))

# COMMAND ----------

# MAGIC %md
# MAGIC ## Step 2 – COPY INTO
# MAGIC
# MAGIC The statement below is generated by `src/common/copy_into.py` (unit tested). Its result shows how
# MAGIC many rows were inserted – **0 on a rerun**, because the files were already loaded.

# COMMAND ----------

copy_sql = build_copy_into_sql(table, source_dir, run_id)
print(copy_sql)

copy_result = spark.sql(copy_sql)
copy_metrics = copy_result.first().asDict()
display(copy_result)
inserted_rows = int(copy_metrics.get("num_inserted_rows") or 0)
print(f"Rows inserted by this run: {inserted_rows:,}")

# COMMAND ----------

# MAGIC %md
# MAGIC ## Step 3 – OPTIMIZE (Liquid Clustering)
# MAGIC
# MAGIC Clusters newly written data by the clustering columns. Safe to run when nothing changed.

# COMMAND ----------

if params["run_optimize"] == "true":
    display(spark.sql(f"OPTIMIZE {table}"))
else:
    print("OPTIMIZE skipped (run_optimize = false)")

# COMMAND ----------

# MAGIC %md
# MAGIC ## Step 4 – Sanity checks
# MAGIC
# MAGIC | # | Check | Expected |
# MAGIC |---|---|---|
# MAGIC | 1 | Rows per source file in the table = rows per file in the chunk folder; same set of files | equal |
# MAGIC | 2 | Files **without** satellite columns: all 9 bands null on every row, `label` only 0/1, and `sum(label)` equals the chunk file's – proves columns were matched **by name** | all true |
# MAGIC | 2b | Files **with** satellite columns: no band is null | 0 nulls |
# MAGIC | 3 | Duplicate natural keys in the table | 0 |
# MAGIC | 4 | Audit columns never null; `ingestion_method` = COPY_INTO | 0 problems |
# MAGIC
# MAGIC The chunk files are counted with the shared reader, which also matches columns by name.

# COMMAND ----------

chunk_files = sorted(n for n in os.listdir(source_dir) if n.endswith(".csv"))
headers = {}
for name in chunk_files:
    with open(f"{source_dir}/{name}", encoding="utf-8") as f:
        headers[f"{source_dir}/{name}"] = parse_header(f.readline())
has_bands = {os.path.basename(p): all(b in h for b in SATELLITE_BANDS) for p, h in headers.items()}

source_stats = {
    r[FILE_NAME_COLUMN]: (r["rows"], r["label_sum"])
    for r in read_csv_by_name(spark, headers, with_file_name=True)
    .groupBy(FILE_NAME_COLUMN)
    .agg(F.count(F.lit(1)).alias("rows"), F.sum("label").alias("label_sum"))
    .collect()
}

bands_null_all = " AND ".join(f"{quote_identifier(b)} IS NULL" for b in SATELLITE_BANDS)
bands_null_any = " OR ".join(f"{quote_identifier(b)} IS NULL" for b in SATELLITE_BANDS)
table_stats = {
    r["source_file"]: r.asDict()
    for r in spark.sql(f"""
        SELECT source_file,
               count(*)                                         AS rows,
               sum(label)                                       AS label_sum,
               count_if({bands_null_all})                       AS rows_all_bands_null,
               count_if({bands_null_any})                       AS rows_any_band_null,
               count_if(label IS NULL OR label NOT IN (0, 1))   AS rows_bad_label
        FROM {table}
        GROUP BY source_file
    """).collect()
}

check_rows, problems = [], []
for name in sorted(set(source_stats) | set(table_stats)):
    src_rows, src_label = source_stats.get(name, (0, None))
    t = table_stats.get(name, {})
    tbl_rows = t.get("rows", 0)
    issues = []
    if name not in source_stats:
        issues.append("in table but not in chunk folder")
    if name not in table_stats:
        issues.append("not loaded")
    if tbl_rows != src_rows:
        issues.append(f"rows {tbl_rows:,} != source {src_rows:,}")
    if t and t["label_sum"] != src_label:
        issues.append(f"sum(label) {t['label_sum']} != source {src_label}")
    if t and t["rows_bad_label"]:
        issues.append(f"{t['rows_bad_label']:,} rows with null/invalid label")
    if t and has_bands.get(name) is False and t["rows_all_bands_null"] != tbl_rows:
        issues.append("satellite bands not null for a file without satellite columns")
    if t and has_bands.get(name) is True and t["rows_any_band_null"]:
        issues.append(f"{t['rows_any_band_null']:,} rows with null bands in a file that has them")
    problems += [f"{name}: {i}" for i in issues]
    check_rows.append((
        name, "yes" if has_bands.get(name) else "no", src_rows, tbl_rows, src_label, t.get("label_sum"),
        t.get("rows_all_bands_null", 0), "OK" if not issues else "; ".join(issues),
    ))

check_df = spark.createDataFrame(
    check_rows,
    "source_file string, has_satellite_columns string, source_rows long, table_rows long, "
    "source_label_sum long, table_label_sum long, rows_all_bands_null long, status string",
)

# COMMAND ----------

# MAGIC %md
# MAGIC **Checks 1 and 2 – per source file** (files without satellite columns first)

# COMMAND ----------

display(check_df.orderBy("has_satellite_columns", "source_file"))

# COMMAND ----------

# MAGIC %md
# MAGIC **Checks 3 and 4 – duplicates and audit columns**

# COMMAND ----------

key_cols = ", ".join(quote_identifier(c) for c in NATURAL_KEY)
duplicate_keys = spark.sql(
    f"SELECT count(*) AS n FROM (SELECT {key_cols} FROM {table} GROUP BY {key_cols} HAVING count(*) > 1)"
).first()["n"]
audit = spark.sql(f"""
    SELECT count_if(source_file IS NULL OR source_file_path IS NULL OR source_file_modified_dt IS NULL
                    OR load_dt IS NULL OR load_run_id IS NULL OR ingestion_method IS NULL) AS rows_null_audit,
           count_if(ingestion_method <> '{INGESTION_METHOD}')                             AS rows_other_method,
           count(DISTINCT load_run_id)                                                     AS load_runs,
           count(*)                                                                        AS total_rows
    FROM {table}
""").first().asDict()

if duplicate_keys:
    problems.append(f"{duplicate_keys:,} duplicate natural keys")
if audit["rows_null_audit"]:
    problems.append(f"{audit['rows_null_audit']:,} rows with a null audit column")
if audit["rows_other_method"]:
    problems.append(f"{audit['rows_other_method']:,} rows with ingestion_method other than {INGESTION_METHOD}")

summary = [
    ("Files in chunk folder", str(len(source_stats))),
    ("Files in table", str(len(table_stats))),
    ("Rows in chunk files", f"{sum(v[0] for v in source_stats.values()):,}"),
    ("Rows in table", f"{audit['total_rows']:,}"),
    ("Rows inserted by this run", f"{inserted_rows:,}"),
    ("Files without satellite columns", ", ".join(sorted(n for n, b in has_bands.items() if not b)) or "none"),
    ("Duplicate natural keys", f"{duplicate_keys:,}"),
    ("Rows with null audit columns", f"{audit['rows_null_audit']:,}"),
    ("Distinct load_run_id values", str(audit["load_runs"])),
    ("Result", "PASS" if not problems else "FAIL"),
]
display(spark.createDataFrame(summary, "check string, value string"))

# COMMAND ----------

if problems:
    raise AssertionError("Bronze COPY INTO sanity check failed:\n- " + "\n- ".join(problems))
print(f"All checks passed: {audit['total_rows']:,} rows from {len(table_stats)} files in {table}.")
